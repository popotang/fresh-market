-- Kemai Yunfan product archive. Prices use yuan; rates use percentage points.
-- Product and barcode codes are text so leading zeroes are preserved.
CREATE TABLE product_items (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  item_code VARCHAR(64) NOT NULL COMMENT '商品编码',
  barcode VARCHAR(64) NOT NULL COMMENT '国际条码/商品条码',
  item_name VARCHAR(255) NOT NULL COMMENT '商品名称',
  audit_status VARCHAR(32) NULL COMMENT '审核状态',
  supplier_code VARCHAR(64) NULL COMMENT '主供应商编码',
  supplier_name VARCHAR(255) NULL COMMENT '主供应商名称',
  brand_code VARCHAR(64) NULL COMMENT '商品品牌编码',
  brand_name VARCHAR(128) NULL COMMENT '商品品牌名称',
  category_code VARCHAR(64) NULL COMMENT '商品类别编码',
  category_name VARCHAR(128) NULL COMMENT '商品类别名称',
  category_level1_code VARCHAR(32) NULL COMMENT '一级类别编码',
  category_level1_name VARCHAR(128) NULL COMMENT '一级类别名称',
  category_level2_code VARCHAR(32) NULL COMMENT '二级类别编码',
  category_level2_name VARCHAR(128) NULL COMMENT '二级类别名称',
  retail_price DECIMAL(18,4) NULL COMMENT '零售价（元）',
  purchase_price DECIMAL(18,4) NULL COMMENT '进货价（元）',
  member_price DECIMAL(18,4) NULL COMMENT '会员价（元）',
  gross_margin_percent DECIMAL(7,2) NULL COMMENT '定价毛利率（百分比）',
  commission_percent DECIMAL(7,2) NULL COMMENT '扣率（百分比）',
  input_tax_percent DECIMAL(7,2) NULL COMMENT '进项税率（百分比）',
  output_tax_percent DECIMAL(7,2) NULL COMMENT '销项税率（百分比）',
  logistics_mode VARCHAR(32) NULL COMMENT '物流模式',
  pricing_method VARCHAR(32) NULL COMMENT '计价方式',
  purchase_unit VARCHAR(32) NULL COMMENT '采购单位',
  remarks TEXT NULL COMMENT '备注',
  source_system VARCHAR(32) NOT NULL DEFAULT 'kemai_yunfan',
  source_item_id VARCHAR(64) NULL COMMENT '云帆商品ID，后续接口同步可补充',
  source_branch_id VARCHAR(64) NULL COMMENT '云帆机构ID，后续接口同步可补充',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_product_items_item_code (item_code),
  UNIQUE KEY uq_product_items_source_item_id (source_item_id),
  KEY idx_product_items_barcode (barcode),
  KEY idx_product_items_supplier_code (supplier_code),
  KEY idx_product_items_category_code (category_code),
  KEY idx_product_items_item_name (item_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci
  COMMENT='科迈云帆商品档案';
